/**
 * Open the branded plan file in a new tab and trigger the print dialog.
 * `bodyHtml` must be the pre-sanitized innerHTML from the chat bubble.
 */
export function openPlanFile(bodyHtml: string, userName: string, lang: string): void {
  const html = buildPlanFileHtml(bodyHtml, userName, lang);
  const win = window.open('', '_blank');
  if (win) {
    win.document.write(html);
    win.document.close();
  }
}

/**
 * Consume one unit of the free-tier monthly file budget.
 *
 * Plan files share the same report_count_month budget as field reports
 * (free = 1/month). Paid tiers are unlimited and never touch the counter.
 *
 * Returns 'paywall' when a free user is out of budget (caller should show the
 * paywall and NOT open the file), or 'ok' when the file may be generated.
 */
export async function consumeReportQuota(
  appUserId: string,
  isFree: boolean,
): Promise<'ok' | 'paywall'> {
  if (!isFree) return 'ok';

  // Lazy import so the pure HTML builder above stays import-safe in unit tests
  // (top-level supabase import instantiates the client at module load).
  const { supabase } = await import('./supabase');

  const { data } = await supabase
    .from('users')
    .select('report_count_month')
    .eq('id', appUserId)
    .single();

  const count = data?.report_count_month ?? 0;
  if (count >= 1) return 'paywall';

  await supabase
    .from('users')
    .update({ report_count_month: count + 1 })
    .eq('id', appUserId);

  return 'ok';
}
