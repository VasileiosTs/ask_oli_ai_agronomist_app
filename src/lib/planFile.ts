/**
 * Branded "save the whole plan as a file" export.
 *
 * The plan is already rendered (and rehype-sanitized) inside the chat bubble.
 * `openPlanFile` takes that pre-rendered, already-safe innerHTML and drops it
 * into an Oli-branded print shell (same header/footer/green as the field
 * report in generateReport.ts), then opens it in a new tab that auto-prints —
 * so the grower can read it, save it as PDF, or print it.
 *
 * Gating decision (matches the field-report behaviour already shipped):
 *   free   → 1 file / month, shared with the report_count_month budget
 *   paid   → unlimited
 */

/** Escape user-controlled strings before inserting into HTML context. */
function h(s: string | null | undefined): string {
  if (s == null) return '';
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

